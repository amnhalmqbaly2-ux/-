    fun getAllBuiltInStories(): List<OmaniStory> =
        listOf(preDiagnosticStory) + curriculumStories + listOf(postDiagnosticStory)

    fun getAllGlossaryWords(customStories: List<OmaniStory> = emptyList()): List<Pair<OmaniWord, String>> {
        val allStories = getAllBuiltInStories() + customStories
        return allStories.flatMap { story ->
            story.vocabulary.map { word -> word to story.title }
        }
    }
